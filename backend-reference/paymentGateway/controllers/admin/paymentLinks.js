const asyncHandler = require("../../middlewares/async");
const { findServiceOperatorByAccessKey } = require("../../utils/checkAndFetchServiceDetails");
const accessKey = 'quick_links'
const axios = require("axios");
const { customLog } = require('../../utils/loggerHelper');
const ErrorResponse = require("../../utils/error-response");
const { createPaymentLink, findOne: findOnePaymentLink, } = require("../../models/use-cases/paymentLink");
const { findOne } = require("../../models/use-cases/corporateUser");
const emailer = require("../../utils/emailer");
const { generatePaymentLinkTemplate } = require("../../utils/emailTemplates/paymentLink");
const { generatePaymentLinkTemplateNew } = require('../../utils/emailTemplates/invoice');
const moment = require('moment');
const sms = require("../../utils/sms");
const { fetchPartnerDetails } = require('../../models/use-cases/systemUser')
const { resolveEmailTemplate } = require('../../services/emailTemplateResolver');
const { EMAIL_TEMPLATE_KEYS, EMAIL_TEMPLATE_SERVICES } = require('../../utils/emailTemplateKeys');
const { v2LayoutVariables } = require('../../utils/emailTemplate/sharedLayout');

exports.createPaymentLink = asyncHandler(async (req, res, next) => {
    try {     
        const serviceDetails = await findServiceOperatorByAccessKey(accessKey);

        if (Object.prototype.hasOwnProperty.call(serviceDetails, 'error')) {
            return next(new ErrorResponse('Apologies, the service you are trying to access is currently unavailable.', 500))
        }
        // Generate a random number between 1000 and 9999
    const random_number = new Date().valueOf();

    // Combine prefix, timestamp, and random number to create the reference_id
    const reference_id = `${random_number}`;

        const {
            corporate,
            service,
            expires_at,
            currency,
            notification,
        } = req.body;
        const corporateDetails = await findOne({ id: corporate });

        const amount = Number(req.body.amount);

        const apiUrl = serviceDetails.vendor.apiUrl
        const consumer_urn = serviceDetails.vendor.optional1
        const client_id = serviceDetails.vendor.optional2;
        const client_secret = serviceDetails.vendor.optional3;

        const corporateName = corporateDetails.name
        const corporateEmail = corporateDetails.email
        const corporateMobile = corporateDetails.mobileNo
        const purpose_message= "createpayment link"
        const customerEmail=corporateEmail
        const formData =
    {
      reference_id,
      consumer_urn,
      amount,
      purpose_message,
      generate_psp_uri: false,
      expiry_time:  Number(expires_at)
    }

        const config = {
             method: "POST",
             url: `${apiUrl}/v3/payments/upi/link`,
             headers: {
               client_id,
               client_secret,
             },
             data: formData,
           };
           customLog(req?.LogTraceId, "info", {
             message: `payment link config`,
             data: config
           });
           const response = await axios(config);
           if (response?.data) {
            const result = response.data.data;
            const firstEntryKey = Object.keys(result.upi_uris)[0];
            const firstEntryValue = result.upi_uris[firstEntryKey];
      

            const sentPayload = {
              full_name: corporateName,
              email: corporateDetails.email,
              phone_number: corporateDetails.mobileNo,
              expires_at: expires_at,
              notification,
              amount: amount,
              currency,
              serviceId: service,
              corporateId: corporate,
          };

            const orderDetails = await createPaymentLink({
              sentPayload: sentPayload,
              paymentLink: firstEntryValue,
              status: 'created',
              invoiceId: response?.data.decentro_txn_id,
              credentialId: req.user.id,
              reference_id,
              amount: parseFloat(amount),
              expireDate: formData.expiry_time,
             // invoiceId
             type: "ADMIN",
            });
           

      
            let partnerDetails;
            partnerDetails = await fetchPartnerDetails(req?.user?.registeredBy);
      
            const subject = `Payment Link Generated by ${corporateName}, Reference ID ${reference_id}`;
      
            // const formatedExipireDate = moment(expiryDate).format("YYYY-MM-DD")
           
            const emailData = {
              amount: parseFloat(amount),
              link: firstEntryValue,
              corporateName,
              invoiceId: reference_id,
              expiryDate: formData.expiry_time
      
            }
            const expiretime = Math.floor(formData.expiry_time / 60)
      
            const body = generatePaymentLinkTemplateNew(emailData, partnerDetails);
            if (notification == 'ALL') {
              emailer.sendEmailForPaymentLink(customerEmail, subject, body, corporateName, function () { })
              sms.sendSMS(`+91${corporateMobile}`,
                `A payment of ₹ ${parseFloat(amount)} has been generated by ${corporateName}. Your Reference ID is ${reference_id}. Please note that this payment request will expire in ${expiretime} hours. To complete the payment, please click the link below: Payment Link: ${firstEntryValue} `)
            } else if (notification == 'EML') {
              emailer.sendEmailForPaymentLink(customerEmail, subject, body, corporateName, function () { })
            } else if (notification == 'SMS') {  
              sms.sendSMS(`+91${corporateMobile}`,   
                `A payment of ₹ ${parseFloat(amount)} has been generated by ${corporateName}. Your Reference ID is ${reference_id}. Please note that this payment request will expire in ${expiretime} hours. To complete the payment, please click the link below: Payment Link: ${firstEntryValue} `)
            }
      
      
            // if (invoiceId) {
            //   await updateInvoice({ id: invoiceId }, { paymentLink: firstEntryValue })
            // }
      
            return res.status(200).json({
              status: true,
              data: {
                paymentLink: firstEntryValue, createdAt: orderDetails?.createdAt, orderId: reference_id, customerName: corporateName,
                expireyDate: orderDetails?.sentPayload?.expires_at
              },
              message: "Payment link generated successfully",
              responseCode: "000",
            });
          } else {
            return next(new ErrorResponse("Something went wrong while generating payment link", 400));
          }
        } catch (error) {
          customLog(req?.LogTraceId, "error", { message: error?.message, data: error?.response?.data })
          return next(new ErrorResponse("Something went wrong while generating payment link", 400));
        }
      });

exports.resendPaymentLink = asyncHandler(async (req, res, next) => {
    try {
        const { paymentRefId } = req.params;

        if (!paymentRefId) {
            return next(new ErrorResponse("Reference ID is missing in the data", 400));
        }
        const orderDetails = await findOnePaymentLink({ invoiceId: paymentRefId });
        if (!orderDetails) {
            return next(new ErrorResponse("Order not found", 404));
        }

        const amount = orderDetails.amount
        const expiryDate = orderDetails.expiryDate
        const email = orderDetails.sentPayload.email
        const link = orderDetails.paymentLink
       // const invoiceId = orderDetails.invoiceId
        const companyName = orderDetails.sentPayload.full_name

        const formatedExipireDate = moment(expiryDate).format("YYYY-MM-DD")

        const subject = "Payment link";
        const partnerData = await fetchPartnerDetails(req?.user?.registeredBy);
        const resolved = await resolveEmailTemplate({
            key: EMAIL_TEMPLATE_KEYS.PAYMENT_LINK_GENERATED,
            service: EMAIL_TEMPLATE_SERVICES.PAYMENT_LINK,
            variables: {
                amount,
                link,
                contactPerson: companyName || 'User',
                branding: partnerData?.branding || 'Peko',
                website: partnerData?.baseUrl || 'https://peko.one/in',
                ...v2LayoutVariables(partnerData),
            },
            fallback: () => generatePaymentLinkTemplate(parseFloat(amount), link, companyName, formatedExipireDate),
            fallbackSubject: subject,
            logTraceId: req?.LogTraceId,
        });
        emailer.email({to: email, subject: resolved.subject, body: resolved.html}, function () { });
        return res.status(200).json({
            status: true,
            message: 'Email sent successfully',
            data: {},
            responseCode: '000'
        });
    } catch (error) {
        console.log("🚀 ~ exports.resendInvoice=asyncHandler ~ error:", error);
        return next(new ErrorResponse("Something went wrong while resending payment link", 400));
    }
});