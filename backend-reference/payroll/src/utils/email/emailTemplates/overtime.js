const { socialIconCells, v2Header, v2Footer, websiteLabel, PEKO_SOCIAL_LINKS } = require('../sharedLayout');

const detailLinesHtml = (lines) =>
  lines.filter(([, value]) => value !== undefined && value !== null && value !== '')
    .map(([label, value]) => `${label}: ${value}`)
    .join('<br />');

const ctaButton = (ctaUrl, label) => ctaUrl ? `<tr>
                                <td align="left" style="font-size:0px;padding-bottom:24px;word-break:break-word;">
                                  <table border="0" cellpadding="0" cellspacing="0" role="presentation" style="border-collapse:separate;line-height:100%;">
                                    <tr>
                                      <td align="center" bgcolor="#FF4F4F" role="presentation" style="border:none;border-radius:10px;cursor:auto;mso-padding-alt:15px 30px;background:#FF4F4F;" valign="middle">
                                        <a href="${ctaUrl}" style="display:inline-block;background:#FF4F4F;color:#ffffff;font-family:'Segoe UI','Helvetica Neue',Arial,sans-serif;font-size:16px;font-weight:600;line-height:100%;margin:0;text-decoration:none;text-transform:none;padding:15px 30px;mso-padding-alt:0px;border-radius:10px;" target="_blank">${label}</a>
                                      </td>
                                    </tr>
                                  </table>
                                </td>
                              </tr>` : '';

const hoursLabel = (overtimeHours) => typeof overtimeHours === 'number'
  ? `${overtimeHours} ${overtimeHours === 1 ? 'hour' : 'hours'}`
  : overtimeHours || null;

