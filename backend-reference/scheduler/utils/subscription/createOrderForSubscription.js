const sequelizeConfig = require("../../configs/database/index");
const { v4: uuidv4 } = require('uuid');

const createOrderForSubscription = async ({
    corporateTxnId,
    operatorId = uuidv4(),
    transactionDate,
    amountInINR,
    baseAmount,
    baseCurrency,
    exchangeRate,
    status,
    paymentMode,
    paymentModeResponse,
    accountNo,
    surcharge,
    serviceOperatorId,
    credentialId,
    subCorporateUserId,
    orderResponse,
    message,
    optional,
    createdAt,
    updatedAt,
    vat,
    pgCharge,
    vendorCost,
    VATP,
    amountSurplus,
    partnerShare,
    actualEarnings
}, transaction) => {
    const createOrderQuery = `
        INSERT INTO orders (
            corporateTxnId,
            operatorId,
            transactionDate,
            amountInINR,
            baseAmount,
            baseCurrency,
            exchangeRate,
            status,
            paymentMode,
            paymentModeResponse,
            accountNo,
            surcharge,
            serviceOperatorId,
            credentialId,
            subCorporateUserId,
            orderResponse,
            message,
            optional,
            vat,
            pgCharge,
            vendorCost,
            VATP,
            amountSurplus,
            partnerShare,
            actualEarnings,
            createdAt,
            updatedAt
        ) VALUES (
            :corporateTxnId,
            :operatorId,
            :transactionDate,
            :amountInINR,
            :baseAmount,
            :baseCurrency,
            :exchangeRate,
            :status,
            :paymentMode,
            :paymentModeResponse,
            :accountNo,
            :surcharge,
            :serviceOperatorId,
            :credentialId,
            :subCorporateUserId,
            :orderResponse,
            :message,
            :optional,
            :vat,
            :pgCharge,
            :vendorCost,
            :VATP,
            :amountSurplus,
            :partnerShare,
            :actualEarnings,
            :createdAt,
            :updatedAt
        );
    `;

    await sequelizeConfig.query(createOrderQuery, {
        replacements: {
            corporateTxnId,
            operatorId,
            transactionDate,
            amountInINR,
            baseAmount,
            baseCurrency,
            exchangeRate,
            status,
            paymentMode,
            paymentModeResponse,
            accountNo,
            surcharge,
            serviceOperatorId,
            credentialId,
            subCorporateUserId,
            orderResponse,
            message,
            optional,
            vat: vat || null,
            pgCharge: pgCharge || null,
            vendorCost: vendorCost || null,
            VATP: VATP || null,
            amountSurplus: amountSurplus || null,
            partnerShare: partnerShare || null,
            actualEarnings: actualEarnings || null,
            createdAt,
            updatedAt
        },
        transaction,
    });
};


// Export the createOrder function
module.exports = {
    createOrderForSubscription,
};
