const DEFAULT_MAX_SIZE_KB = 10 * 1024

const MAX_TOTAL_UPLOAD_KB = 25 * 1024

const MAX_VENDOR_PACK_KB = 26 * 1024

const serializeDocument = (doc) => ({
    key: doc.key,
    documentName: doc.documentName,
    label: doc.label,
    uploadLabel: doc.uploadLabel,
    hint: doc.hint,
    required: doc.required !== false,
    maxSizeKb: doc.maxSizeKb || DEFAULT_MAX_SIZE_KB,
})

const BUSINESS_TYPES = BUSINESS_TYPE_CHECKLISTS.map((entry) => entry.value)

/** Applications saved before Private and Public Limited were split still resolve to a checklist. */
const LEGACY_BUSINESS_TYPES = { PRIVATE_PUBLIC_LIMITED: 'PRIVATE_LIMITED' }

const resolveBusinessType = (businessType) => LEGACY_BUSINESS_TYPES[businessType] || businessType

const checklistFor = (businessType) => {
    const resolved = resolveBusinessType(businessType)
    return BUSINESS_TYPE_CHECKLISTS.find((entry) => entry.value === resolved) || null
}

/**
 * Every document name any checklist can ask for, plus the corporate agreement. This is what the upload
 * endpoint accepts and what the reviewer's listing filters on, so deriving it here means a document added
 * to a checklist is automatically uploadable and visible instead of being silently rejected.
 */
const ALL_DOCUMENT_NAMES = [
    ...new Set([
        ...BUSINESS_TYPE_CHECKLISTS.flatMap((entry) => entry.documents.map((doc) => doc.documentName)),
        DOC.CORPORATE_AGREEMENT.documentName,
        DOC.ADDRESS_PROOF.documentName,
    ]),
]

const AGREEMENT_DOCUMENT_NAMES = [DOC.CORPORATE_AGREEMENT.documentName, DOC.ADDRESS_PROOF.documentName]

const SYSTEM_DOCUMENT_NAMES = [
    DOC.CORPORATE_AGREEMENT_GENERATED.documentName,
    DOC.CORPORATE_AGREEMENT_SIGNED.documentName,
]

const REVIEWABLE_DOCUMENT_NAMES = [...ALL_DOCUMENT_NAMES, ...SYSTEM_DOCUMENT_NAMES]

/**
 * What the vendor receives. The form-filled agreement is the unsigned draft Peko generates to send for
 * e-signature; it is kept for internal review but is not evidence of anything, and putting a second
 * near-identical agreement in front of the vendor invites them to review the wrong one.
 */
const VENDOR_PACK_DOCUMENT_NAMES = REVIEWABLE_DOCUMENT_NAMES.filter(
    (name) => name !== DOC.CORPORATE_AGREEMENT_GENERATED.documentName
)

const DOCUMENTS_BY_NAME = Object.values(DOC).reduce(
    (byName, doc) => ({ ...byName, [doc.documentName]: doc }),
    {}
)

/**
 * The reviewer's list for one corporate: the documents its constitution asks for, then the
 * agreement-scoped ones. Derived so a document added to a checklist becomes visible to reviewers
 * instead of silently missing from their screen.
 *
 * With no business type there is no checklist to hold the corporate to, so the list is what it actually
 * uploaded plus the two documents every constitution needs. Listing all fifteen instead would paint a
 * dozen red "Missing" rows that mean nothing, and reviewers would learn to ignore the tag.
 */
const isRequiredForReview = (documentName, doc, checklist, { addressProofSameAsGst, agreementSignMethod }) => {
    if (documentName === DOC.CORPORATE_AGREEMENT.documentName) {
        return agreementSignMethod === AGREEMENT_SIGN_METHOD.UPLOAD
    }
    if (documentName === DOC.ADDRESS_PROOF.documentName && addressProofSameAsGst) return false
    return checklist ? doc.required !== false : AGREEMENT_DOCUMENT_NAMES.includes(documentName)
}

const reviewChecklistFor = (
    businessType,
    uploadedDocumentNames = [],
    { addressProofSameAsGst = false, agreementSignMethod = null } = {}
) => {
    const checklist = checklistFor(businessType)

    const agreementNames = AGREEMENT_DOCUMENT_NAMES.filter(
        (name) =>
            name !== DOC.CORPORATE_AGREEMENT.documentName
            || agreementSignMethod === AGREEMENT_SIGN_METHOD.UPLOAD
            || uploadedDocumentNames.includes(name)
    )

    const names = checklist
        ? [
            ...checklist.documents.map((doc) => doc.documentName),
            ...agreementNames,
            ...SYSTEM_DOCUMENT_NAMES,
        ]
        : [
            ...REVIEWABLE_DOCUMENT_NAMES.filter((name) => uploadedDocumentNames.includes(name)),
            ...agreementNames,
            ...SYSTEM_DOCUMENT_NAMES,
        ]

    return [...new Set(names)].map((documentName) => {
        const doc = DOCUMENTS_BY_NAME[documentName] || {}
        // Outside a known checklist only the agreement documents can be called for; anything else the
        // corporate uploaded is evidence, not an obligation we can assert.
        const required = isRequiredForReview(documentName, doc, checklist, {
            addressProofSameAsGst,
            agreementSignMethod,
        })
        return {
            documentName,
            label: doc.label || documentName.replace(/_/g, ' '),
            required,
        }
    })
}

const maxSizeKbFor = (documentName) =>
    DOCUMENTS_BY_NAME[documentName]?.maxSizeKb || DEFAULT_MAX_SIZE_KB

