/**
 * Customer-facing Corporate Cards emails, from the support team's approved copy deck.
 *
 * Every mail carries the Pine Labs issuer disclaimer — it is a compliance line on the deck, not
 * decoration, so it lives here rather than in any one template.
 *
 * AUTO keys are sent by the flow that causes them, WEBHOOK keys by a Pine Labs callback, and SWEEP
 * keys by a scheduled job that looks for a condition nobody raises — an approved corporate that has
 * never funded its wallet has no moment to react to, only an absence to notice.
 *
 * MANUAL keys have no signal this service can read — the courier reports dispatch but never delivery,
 * and nothing records whether a delivered card was ever activated — so support sends those by hand.
 */

