const router = require('express').Router({ mergeParams: true })
const { verifyToken } = require('../../../../utils/jwtToken')
const { verifySystemUser } = require('../../../../middlewares/verifySystemUser')
const { listApplications, getSummary, listCorporates, getApplication, updateApplication, retryVendorEmail } = require('../../../../controllers/systemUser/corporateCardApplication')
const { listTerminationRequests, completeTermination } = require('../../../../controllers/systemUser/cardTermination')
const { listStuckIssuances, forceReconcileIssuance, runReconcileSweep } = require('../../../../controllers/systemUser/cardOrderReconcile')
const { listAccountClosureRequests, approveAccountClosure, rejectAccountClosure } = require('../../../../controllers/systemUser/accountClosure')
const { runPendingKycSweep, runWeeklySpendDigestSweep, runDailyBalanceReminderSweep, runWalletTopupGuideSweep } = require('../../../../controllers/systemUser/notificationJobs')
const { getDocumentSizeLimits, updateDocumentSizeLimits } = require('../../../../controllers/systemUser/documentSizeLimits')
const { listTransactions, getTransaction, listTransactionCorporates } = require('../../../../controllers/systemUser/cardTransactions')
const { getCorporateLookup, listLookupActivity, listLookupRequests, listLookupTopUps, listLookupDispatches } = require('../../../../controllers/systemUser/corporateCardLookup')
const { listSupportEmailTemplates, sendSupportEmail } = require('../../../../controllers/systemUser/supportEmails')

router.use(verifyToken)
router.use(verifySystemUser)

router.get('/applications', listApplications)
router.get('/applications/summary', getSummary)
router.get('/corporates', listCorporates)
router.get('/applications/:corporateId', getApplication)
router.put('/applications/:corporateId', updateApplication)
router.post('/applications/:corporateId/vendor-email/retry', retryVendorEmail)
router.get('/termination-requests', listTerminationRequests)
router.put('/termination-requests/:id/complete', completeTermination)
router.get('/account-closure-requests', listAccountClosureRequests)
router.put('/account-closure-requests/:id/approve', approveAccountClosure)
router.put('/account-closure-requests/:id/reject', rejectAccountClosure)
router.post('/notifications/pending-kyc-sweep', runPendingKycSweep)
router.post('/notifications/weekly-spend-digest-sweep', runWeeklySpendDigestSweep)
router.post('/notifications/daily-balance-reminder-sweep', runDailyBalanceReminderSweep)
router.post('/notifications/wallet-topup-guide-sweep', runWalletTopupGuideSweep)
router.get('/card-issuances/stuck', listStuckIssuances)
router.post('/card-issuances/reconcile-sweep', runReconcileSweep)
router.post('/card-issuances/:cardIssuanceId/reconcile', forceReconcileIssuance)
router.get('/transactions', listTransactions)
router.get('/transactions/corporates', listTransactionCorporates)
router.get('/transactions/:id', getTransaction)
router.get('/lookup/:corporateId', getCorporateLookup)
router.get('/lookup/:corporateId/activity', listLookupActivity)
router.get('/lookup/:corporateId/requests', listLookupRequests)
router.get('/lookup/:corporateId/top-ups', listLookupTopUps)
router.get('/lookup/:corporateId/dispatches', listLookupDispatches)
router.get('/support-emails/templates', listSupportEmailTemplates)
router.post('/support-emails/send', sendSupportEmail)
router.get('/document-size-limits', getDocumentSizeLimits)
router.put('/document-size-limits', updateDocumentSizeLimits)
router.use("/corporate-documents",require("./corporateDocuments"))
router.use("/corporate-agreement",require("./corporateAgreement"))
router.use("/document",require("../corporate/document"))

module.exports = router
